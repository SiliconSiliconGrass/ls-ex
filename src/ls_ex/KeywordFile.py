"""整个 .k 文件的读写，以及常用数据（节点、单元）的提取。"""

from __future__ import annotations

import re
from contextlib import nullcontext
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator, Sequence

from .KCard import KCard
from .KWord import KWord

#: 从定长字段里抠数字用的正则（兼容 ``1.0-2.0`` 这种没有空格的写法）
NUMBER_RE = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eEdD][-+]?\d+)?")

Vec3 = tuple[float, float, float]
Solid = tuple[int, int, tuple[int, ...]]
Shell = tuple[int, int, tuple[int, ...]]

#: Keyword blocks that contain the finite-element mesh rather than model setup.
GEOMETRY_KEYWORDS = frozenset({
    "NODE",
    "ELEMENT_SOLID",
    "ELEMENT_SHELL",
    "SET_SEGMENT",
})


def parse_numbers(line: str) -> list[float]:
    """把一行 card 里的数值都读出来。

    先按空白切分；只要有字段不是一个合法数字（定长格式下两个数可能连着写），
    就退回用正则扫描整行。``1.5d-3`` 这种 LS-DYNA 的 D 指数也会被接受。
    """
    text = line.split("$")[0]
    tokens = text.split()
    try:
        return [float(token.replace("d", "e").replace("D", "E")) for token in tokens]
    except ValueError:
        return [float(token.replace("d", "e").replace("D", "E"))
                for token in NUMBER_RE.findall(text)]


@dataclass
class KeywordFile:
    """一个 .k 文件：开头的注释行 + 若干关键字块。"""

    keywords: list[KWord] = field(default_factory=list)
    header: list[str] = field(default_factory=list)

    # ------------------------------------------------------------ 基本操作
    def get(self, name: str) -> KWord | None:
        """按名字取第一个关键字块（名字大小写不敏感）。"""
        wanted = name.upper()
        for keyword in self.keywords:
            if keyword.name.upper() == wanted:
                return keyword
        return None

    def get_all(self, name: str) -> list[KWord]:
        wanted = name.upper()
        return [keyword for keyword in self.keywords if keyword.name.upper() == wanted]

    def add(self, keyword: KWord) -> KWord:
        self.keywords.append(keyword)
        return keyword

    def add_include(self, filename: str) -> KWord:
        """Add an ``*INCLUDE`` block for a deck-relative file."""
        filename = filename.strip().replace("\\", "/")
        if not filename:
            raise ValueError("include filename must not be empty")
        if "\n" in filename or "\r" in filename:
            raise ValueError("include filename must be a single line")
        return self.add(KWord("INCLUDE", [
            KCard(values=[filename], widths=[80], kinds=["s"]),
        ]))

    def split_geometry(
        self,
        include_name: str,
        *,
        geometry_keywords: Sequence[str] = tuple(GEOMETRY_KEYWORDS),
    ) -> tuple["KeywordFile", "KeywordFile"]:
        """Split this deck into an entry deck and an include-compatible mesh deck.

        The returned tuple is ``(entry, geometry)``. The include is inserted
        where the first geometry block appeared, preserving the normal
        LS-DYNA keyword ordering. Repeated mesh blocks remain separate so this
        also works with decks containing several disjoint NODE blocks.
        """
        wanted = {name.upper() for name in geometry_keywords}
        if not wanted:
            raise ValueError("at least one geometry keyword is required")

        geometry = KeywordFile(header=[
            "$# LS-DYNA geometry include generated by ls_ex",
            f"$# include source entry={include_name}",
            f"$# geometry keywords={','.join(sorted(wanted))}",
        ])
        entry = KeywordFile(header=list(self.header))
        include_added = False
        for keyword in self.keywords:
            if keyword.name.upper() not in wanted:
                entry.add(keyword)
                continue
            geometry.add(keyword)
            if not include_added:
                entry.add_include(include_name)
                include_added = True

        if not include_added:
            raise ValueError(
                "deck contains none of the requested geometry keywords: "
                + ", ".join(sorted(wanted))
            )
        return entry, geometry

    # --------------------------------------------------------------- 渲染
    def dumps(self) -> str:
        blocks = [line.rstrip() for line in self.header]
        blocks.extend(keyword.render() for keyword in self.keywords)
        return "\n".join(blocks) + "\n"

    def write(self, path: str | Path, newline: str = "\n") -> Path:
        """写文件，默认用 LF 换行（和 LS-PrePost 导出的 test1.k 一致）。"""
        path = Path(path)
        text = self.dumps()
        if newline != "\n":
            text = text.replace("\n", newline)
        path.write_text(text, encoding="utf-8", newline="")
        return path

    # --------------------------------------------------------------- 解析
    @classmethod
    def loads(cls, text: str) -> "KeywordFile":
        header: list[str] = []
        keywords: list[KWord] = []
        current: KWord | None = None
        for raw_line in text.splitlines():
            line = raw_line.rstrip()
            if line.startswith("*"):
                current = KWord(name=line[1:].strip())
                keywords.append(current)
            elif current is None:
                if line.strip():
                    header.append(line)
            else:
                current.cards.append(KCard.parse(line))
        return cls(keywords=keywords, header=header)

    @classmethod
    def load(cls, path: str | Path) -> "KeywordFile":
        return cls.loads(Path(path).read_text(encoding="utf-8", errors="replace"))

    @classmethod
    def load_resolved(
        cls,
        path: str | Path,
        *,
        include_paths: Sequence[str | Path] = (),
        _seen: frozenset[Path] | None = None,
    ) -> "KeywordFile":
        """Load a deck and recursively replace ``*INCLUDE`` blocks.

        Include names are resolved relative to the including file first, then
        against ``include_paths``. ``*INCLUDE_PATH`` is supported so decks
        exported by LS-DYNA can opt into additional search roots.
        """
        path = Path(path).expanduser().resolve()
        seen = set(_seen or ())
        if path in seen:
            raise ValueError(f"cyclic *INCLUDE detected at {path}")
        seen.add(path)

        deck = cls.load(path)
        search_paths = [Path(item).expanduser().resolve() for item in include_paths]
        combined_search = [path.parent, *search_paths]
        resolved: list[KWord] = []
        for keyword in deck.keywords:
            upper = keyword.name.upper()
            if upper == "INCLUDE_PATH":
                for card in keyword.data_cards:
                    value = card.render().strip().strip("\"'")
                    if value:
                        search_paths.append(path.parent / value)
                        combined_search.append(path.parent / value)
                resolved.append(keyword)
                continue
            if upper == "INCLUDE_TRANSFORM":
                raise NotImplementedError(
                    "*INCLUDE_TRANSFORM is not supported; use *INCLUDE"
                )
            if upper != "INCLUDE":
                resolved.append(keyword)
                continue

            include_name = _include_filename(keyword)
            candidates = [
                root / include_name for root in combined_search
            ]
            include_path = next(
                (candidate.resolve() for candidate in candidates if candidate.is_file()),
                None,
            )
            if include_path is None:
                raise FileNotFoundError(
                    f"{path}: included file {include_name!r} was not found"
                )
            included = cls.load_resolved(
                include_path,
                include_paths=tuple(search_paths),
                _seen=frozenset(seen),
            )
            resolved.extend(
                included_keyword
                for included_keyword in included.keywords
                if included_keyword.name.upper() not in {"KEYWORD", "END"}
            )

        deck.keywords = resolved
        return deck

    # ------------------------------------------------------ 常用数据提取
    def nodes(self) -> dict[int, Vec3]:
        """``*NODE`` 里的节点坐标：``{nid: (x, y, z)}``。"""
        keyword = self.get("NODE")
        result: dict[int, Vec3] = {}
        if keyword is None:
            return result
        for card in keyword.data_cards:
            values = parse_numbers(card.render())
            if len(values) >= 4:
                result[int(values[0])] = (values[1], values[2], values[3])
        return result

    def _elements(self, name: str, node_count: int) -> dict[int, tuple[int, tuple[int, ...]]]:
        keyword = self.get(name)
        result: dict[int, tuple[int, tuple[int, ...]]] = {}
        if keyword is None:
            return result
        for card in keyword.data_cards:
            values = parse_numbers(card.render())
            if len(values) >= 2 + node_count:
                eid = int(values[0])
                pid = int(values[1])
                nodes = tuple(int(value) for value in values[2:2 + node_count])
                result[eid] = (pid, nodes)
        return result

    def solid_elements(self) -> dict[int, tuple[int, tuple[int, ...]]]:
        """``*ELEMENT_SOLID``：``{eid: (pid, (n1..n8))}``。"""
        return self._elements("ELEMENT_SOLID", 8)

    def shell_elements(self) -> dict[int, tuple[int, tuple[int, ...]]]:
        """``*ELEMENT_SHELL``：``{eid: (pid, (n1..n4))}``。"""
        return self._elements("ELEMENT_SHELL", 4)

    def parts(self) -> dict[int, dict[str, int]]:
        """``*PART`` 定义：``{pid: {"secid": .., "mid": .., "title": ..}}``。"""
        result: dict[int, dict[str, int]] = {}
        for keyword in self.get_all("PART"):
            cards = keyword.data_cards
            if len(cards) < 2:
                continue
            title = cards[0].render()
            values = parse_numbers(cards[1].render())
            if not values:
                continue
            pid = int(values[0])
            result[pid] = {
                "title": title.strip(),
                "secid": int(values[1]) if len(values) > 1 else 0,
                "mid": int(values[2]) if len(values) > 2 else 0,
            }
        return result

    def iter_keyword_names(self) -> Iterator[str]:
        for keyword in self.keywords:
            yield keyword.name

    def summary(self) -> str:
        """给命令行用的一行摘要。"""
        return (f"keywords={len(self.keywords)} nodes={len(self.nodes())} "
                f"solids={len(self.solid_elements())} "
                f"shells={len(self.shell_elements())}")


def _include_filename(keyword: KWord) -> str:
    """Return the filename card from an ``*INCLUDE``-like keyword."""
    for card in keyword.data_cards:
        value = card.render().strip()
        if value:
            return value.strip("\"'")
    raise ValueError(f"*{keyword.name} has no filename card")


def split_geometry_include(
    source: str | Path,
    geometry_path: str | Path,
    entry_path: str | Path,
    *,
    include_name: str | None = None,
    geometry_keywords: Sequence[str] = tuple(GEOMETRY_KEYWORDS),
    write_geometry: bool = True,
) -> tuple[Path, Path]:
    """Stream a large deck into an entry file and a geometry include.

    Unlike :meth:`KeywordFile.split_geometry`, this function holds only one
    input line at a time. It is intended for multi-hundred-megabyte ALE decks
    where constructing Python objects for every mesh card would be excessive.
    """
    source = Path(source)
    geometry_path = Path(geometry_path)
    entry_path = Path(entry_path)
    wanted = {name.upper() for name in geometry_keywords}
    if not wanted:
        raise ValueError("at least one geometry keyword is required")
    include_name = include_name or geometry_path.name
    include_name = include_name.replace("\\", "/")
    if (
        not include_name
        or "\n" in include_name
        or "\r" in include_name
    ):
        raise ValueError("include_name must be a non-empty single line")

    geometry_path.parent.mkdir(parents=True, exist_ok=True)
    entry_path.parent.mkdir(parents=True, exist_ok=True)
    include_added = False
    target = "entry"

    geometry_context = (
        geometry_path.open("w", encoding="utf-8", newline="")
        if write_geometry
        else nullcontext(None)
    )
    with (
        source.open("r", encoding="utf-8", errors="replace") as source_file,
        geometry_context as geometry_file,
        entry_path.open("w", encoding="utf-8", newline="") as entry_file,
    ):
        if geometry_file is not None:
            geometry_file.write(
                "$# LS-DYNA geometry include generated by ls_ex\n"
                f"$# geometry source={source.name}\n"
                f"$# geometry keywords={','.join(sorted(wanted))}\n"
            )
        for raw_line in source_file:
            line = raw_line.rstrip("\r\n")
            if line.startswith("*"):
                keyword_name = line[1:].split(maxsplit=1)[0].upper()
                is_geometry = keyword_name in wanted
                target = "geometry" if is_geometry else "entry"
                if is_geometry:
                    if geometry_file is not None:
                        geometry_file.write(line + "\n")
                    if not include_added:
                        entry_file.write(
                            "*INCLUDE\n"
                            "$# include filename\n"
                            f"{include_name}\n"
                        )
                        include_added = True
                else:
                    entry_file.write(line + "\n")
                continue

            if target == "geometry":
                if geometry_file is not None:
                    geometry_file.write(line + "\n")
            else:
                entry_file.write(line + "\n")

    if not include_added:
        raise ValueError(
            "deck contains none of the requested geometry keywords: "
            + ", ".join(sorted(wanted))
        )
    return entry_path, geometry_path
